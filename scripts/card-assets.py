# Regenerates src/app/api/card/assets.ts from public/fonts/*.woff and public/icon-512.png
import base64
def b(p): return base64.b64encode(open(p,'rb').read()).decode()
out = '// Generated by scripts/card-assets.py — fonts (fontsource, OFL) and crest inlined so the card renderer needs no network.\n'
out += f'export const crestDataUri = "data:image/png;base64,{b("public/icon-512.png")}";\n'
for k,f in [("cinzelX","cinzel-700.woff"),("cinzel","cinzel-700-latin.woff"),("ss4X","ss-400.woff"),("ss6X","ss-600.woff"),("ss7X","ss-700.woff"),("ss4","ss-400-latin.woff"),("ss6","ss-600-latin.woff"),("ss7","ss-700-latin.woff")]:
    out += f'export const {k}B64 = "{b("public/fonts/"+f)}";\n'
open('src/app/api/card/assets.ts','w').write(out)
